import { createSlice, createAsyncThunk, PayloadAction } from '@reduxjs/toolkit';

// Types
export interface Symptom {
  id: string;
  name: string;
  severity: number; // 1-10
  duration: string;
  onset: string;
  notes?: string;
}

export interface VitalSigns {
  temperature: number | null;
  bloodPressure: {
    systolic: number | null;
    diastolic: number | null;
  };
  pulse: number | null;
  respiratoryRate: number | null;
  spO2: number | null;
  weight: number | null;
  height: number | null;
  bmi?: number;
  timestamp: string;
}

export interface ClinicalFinding {
  system: string;
  finding: string;
  location?: string;
  notes?: string;
  abnormal: boolean;
}

export interface DiagnosisSuggestion {
  id: string;
  name: string;
  probability: number; // 0-1
  confidence: 'high' | 'medium' | 'low';
  evidence: string[];
  icd10Code?: string;
  treatmentGuidance?: string;
  urgent?: boolean;
}

export interface PrescriptionItem {
  id: string;
  drugId: string;
  name: string;
  dosage: string;
  frequency: string;
  duration: string;
  quantity: number;
  instructions: string;
  formularyAvailable: boolean;
  insuranceCovered: boolean;
  warnings?: string[];
}

export interface LabOrder {
  id: string;
  testId: string;
  testName: string;
  priority: 'routine' | 'urgent' | 'stat';
  specimenType: string;
  instructions?: string;
  status: 'pending' | 'in-progress' | 'completed' | 'cancelled';
  result?: string | number;
  orderedAt: string;
  completedAt?: string;
}

export interface DepartmentTransfer {
  fromDepartment: string;
  toDepartment: string;
  reason: string;
  priority: string;
  timestamp: string;
  staffId: string;
}

export interface ClinicalEncounter {
  id: string;
  patientId: string;
  facilityId: string;
  encounterType: 'outpatient' | 'inpatient' | 'emergency';
  status: 'in-progress' | 'completed' | 'cancelled' | 'forwarded';
  chiefComplaint: string;
  symptoms: Symptom[];
  vitalSigns: VitalSigns[];
  clinicalFindings: ClinicalFinding[];
  diagnosis: DiagnosisSuggestion[];
  differentialDiagnosis: DiagnosisSuggestion[];
  prescriptions: PrescriptionItem[];
  labOrders: LabOrder[];
  clinicalNotes: {
    hpi: string;
    assessment: string;
    plan: string;
    autoGenerated: boolean;
    editedBy?: string;
    editedAt?: string;
  };
  departmentTransfers: DepartmentTransfer[];
  billingItems: Array<{
    itemId: string;
    description: string;
    cost: number;
    quantity: number;
    department: string;
    priority?: string;
  }>;
  allergies: Array<{
    allergen: string;
    reaction: string;
    severity: 'mild' | 'moderate' | 'severe';
    documentedAt: string;
  }>;
  currentMedications: Array<{
    name: string;
    dosage: string;
    frequency: string;
    startDate: string;
  }>;
  aiContext: {
    localDiseasePrevalence: Record<string, number>;
    seasonalPatterns: string[];
    patientHistoryContext: string[];
    communityAlerts: string[];
  };
  createdAt: string;
  updatedAt: string;
  attendingClinician: string;
}

interface ClinicalEncounterState {
  currentEncounter: ClinicalEncounter | null;
  encounters: ClinicalEncounter[];
  aiSuggestions: {
    diagnoses: DiagnosisSuggestion[];
    prescriptions: PrescriptionItem[];
    alerts: Array<{
      type: 'allergy' | 'interaction' | 'abnormal' | 'warning';
      message: string;
      severity: 'info' | 'warning' | 'danger';
    }>;
  };
  loading: boolean;
  error: string | null;
  departmentQueues: Record<string, Array<{
    encounterId: string;
    patientId: string;
    patientName: string;
    priority: string;
    task: string;
    arrivalTime: string;
  }>>;
}

