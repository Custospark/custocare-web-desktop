// Async thunks
export const generateAIDiagnosis = createAsyncThunk(
  'clinicalEncounter/generateAIDiagnosis',
  async (symptoms: Symptom[]) => {
    // Mock AI diagnosis generation
    await new Promise(resolve => setTimeout(resolve, 500));
    
    const suggestions = mockDiagnoses.map(diag => ({
      ...diag,
      probability: Math.random() * 0.8 + 0.2, // 0.2-1.0
      confidence: ['high', 'medium', 'low'][Math.floor(Math.random() * 3)] as 'high' | 'medium' | 'low',
      evidence: symptoms.slice(0, 2).map(s => s.name),
    }));
    
    return suggestions.sort((a, b) => b.probability - a.probability).slice(0, 5);
  }
);

export const checkDrugInteractions = createAsyncThunk(
  'clinicalEncounter/checkDrugInteractions',
  async (payload: { medications: string[]; allergies: string[] }) => {
    // Mock drug interaction check
    await new Promise(resolve => setTimeout(resolve, 300));
    
    const warnings = [];
    if (payload.medications.includes('Ciprofloxacin') && payload.medications.includes('Metformin')) {
      warnings.push({
        type: 'interaction' as const,
        message: 'Ciprofloxacin interacts with Metformin. Increases risk of hypoglycemia.',
        severity: 'danger' as const,
      });
    }
    
    if (payload.allergies.includes('Penicillin') && payload.medications.some(m => m.includes('Penicillin'))) {
      warnings.push({
        type: 'allergy' as const,
        message: 'Patient allergic to Penicillin. Consider alternative antibiotic.',
        severity: 'danger' as const,
      });
    }
    
    return warnings;
  }
);

export const forwardToDepartment = createAsyncThunk(
  'clinicalEncounter/forwardToDepartment',
  async (payload: {
    encounterId: string;
    fromDepartment: string;
    toDepartment: string;
    reason: string;
    priority?: string;
  }) => {
    // Mock API call
    await new Promise(resolve => setTimeout(resolve, 200));
    
    return {
      ...payload,
      timestamp: new Date().toISOString(),
      staffId: 'current-user-id',
    };
  }
);

const initialState: ClinicalEncounterState = {
  currentEncounter: null,
  encounters: [],
  aiSuggestions: {
    diagnoses: [],
    prescriptions: [],
    alerts: [],
  },
  departmentQueues: {
    laboratory: [],
    pharmacy: [],
    radiology: [],
    billing: [],
  },
  loading: false,
  error: null,
};

      // Helper function to create a valid DepartmentTransfer
      const createDepartmentTransfer = (payload: {
        timestamp: string;
        staffId: string;
        encounterId: string;
        fromDepartment: string;
        toDepartment: string;
        reason: string;
        priority?: string;
      }): DepartmentTransfer => ({
        ...payload,
        priority: payload.priority || 'routine',
        // Add any other required fields with defaults
      });

const clinicalEncounterSlice = createSlice({
  name: 'clinicalEncounter',
  initialState,
  reducers: {
    setCurrentEncounter: (state, action: PayloadAction<ClinicalEncounter>) => {
      state.currentEncounter = action.payload;
    },
    
    updateSymptoms: (state, action: PayloadAction<Symptom[]>) => {
      if (state.currentEncounter) {
        state.currentEncounter.symptoms = action.payload;
        state.currentEncounter.updatedAt = new Date().toISOString();
      }
    },
    
    addVitalSigns: (state, action: PayloadAction<VitalSigns>) => {
      if (state.currentEncounter) {
        state.currentEncounter.vitalSigns.push(action.payload);
        state.currentEncounter.updatedAt = new Date().toISOString();
      }
    },
    
    addClinicalFinding: (state, action: PayloadAction<ClinicalFinding>) => {
      if (state.currentEncounter) {
        state.currentEncounter.clinicalFindings.push(action.payload);
        state.currentEncounter.updatedAt = new Date().toISOString();
      }
    },
    
    addPrescription: (state, action: PayloadAction<PrescriptionItem>) => {
      if (state.currentEncounter) {
        state.currentEncounter.prescriptions.push(action.payload);
        state.currentEncounter.updatedAt = new Date().toISOString();
      }
    },
    
    addLabOrder: (state, action: PayloadAction<LabOrder>) => {
      if (state.currentEncounter) {
        state.currentEncounter.labOrders.push(action.payload);
        state.currentEncounter.updatedAt = new Date().toISOString();
      }
    },
    
    updateClinicalNotes: (state, action: PayloadAction<{
      hpi?: string;
      assessment?: string;
      plan?: string;
    }>) => {
      if (state.currentEncounter) {
        state.currentEncounter.clinicalNotes = {
          ...state.currentEncounter.clinicalNotes,
          ...action.payload,
          autoGenerated: false,
          editedBy: 'current-user',
          editedAt: new Date().toISOString(),
        };
        state.currentEncounter.updatedAt = new Date().toISOString();
      }
    },
    
    addToDepartmentQueue: (state, action: PayloadAction<{
      department: string;
      patient: {
        encounterId: string;
        patientId: string;
        patientName: string;
        priority: string;
        task: string;
      };
    }>) => {
      const { department, patient } = action.payload;
      if (!state.departmentQueues[department]) {
        state.departmentQueues[department] = [];
      }
      
      state.departmentQueues[department].push({
        ...patient,
        arrivalTime: new Date().toISOString(),
      });
    },
    
    removeFromDepartmentQueue: (state, action: PayloadAction<{
      department: string;
      encounterId: string;
    }>) => {
      const { department, encounterId } = action.payload;
      if (state.departmentQueues[department]) {
        state.departmentQueues[department] = state.departmentQueues[department].filter(
          item => item.encounterId !== encounterId
        );
      }
    },
    
    clearAISuggestions: (state) => {
      state.aiSuggestions = {
        diagnoses: [],
        prescriptions: [],
        alerts: [],
      };
    },
    
    resetEncounter: (state) => {
      state.currentEncounter = null;
      state.aiSuggestions = {
        diagnoses: [],
        prescriptions: [],
        alerts: [],
      };
    },
  },
  extraReducers: (builder) => {
    builder
      .addCase(generateAIDiagnosis.pending, (state) => {
        state.loading = true;
      })
      .addCase(generateAIDiagnosis.fulfilled, (state, action) => {
        state.loading = false;
        state.aiSuggestions.diagnoses = action.payload;
      })
      .addCase(generateAIDiagnosis.rejected, (state, action) => {
        state.loading = false;
        state.error = action.error.message || 'Failed to generate diagnosis';
      })
      .addCase(checkDrugInteractions.fulfilled, (state, action) => {
        state.aiSuggestions.alerts = [
          ...state.aiSuggestions.alerts,
          ...action.payload,
        ];
      })

        // In your reducer
        .addCase(forwardToDepartment.fulfilled, (state, action) => {
          if (state.currentEncounter) {
            const validTransfer = createDepartmentTransfer(action.payload);
            state.currentEncounter.departmentTransfers.push(validTransfer);
            state.currentEncounter.status = 'forwarded';
            state.currentEncounter.updatedAt = new Date().toISOString();
          }
})
  },
});

export const {
  setCurrentEncounter,
  updateSymptoms,
  addVitalSigns,
  addClinicalFinding,
  addPrescription,
  addLabOrder,
  updateClinicalNotes,
  addToDepartmentQueue,
  removeFromDepartmentQueue,
  clearAISuggestions,
  resetEncounter,
} = clinicalEncounterSlice.actions;

export default clinicalEncounterSlice.reducer;